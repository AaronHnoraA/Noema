export function createEmacsApiHandlers({
  apiOpenInEmacs,
  apiOpenSurface,
  apiSelectJupyterCell,
	apiOpenResearchSession = () => ({ ok: false }),
  apiCurrentFile,
  apiEmacsInputFocus,
  apiEmacsUiState,
  apiEmacsKey,
  apiEmacsSelection = () => ({ ok: false, message: "Emacs selection bridge unavailable" }),
  apiPi = () => ({ ok: false, message: "Emacs Pi bridge unavailable" }),
  apiAgent = () => ({ ok: false, message: "Emacs Agent bridge unavailable" }),
  apiSystemOpen,
  apiEmacsZotero,
  apiChooseNotePath,
}) {
  const documented = (handler, apiDoc) => Object.assign(handler, { apiDoc });
  return {
    "noema:api:emacs:open": documented((body) => apiOpenInEmacs(body?.file ?? body, body?.line, body?.col, body?.tag, body), {
      description: "Open a file in Emacs through the emacsopen placement owner. Agent calls default to another window, preserving the chat; reuse an existing view of the file. Placed visits return the actual buffer/window/frame and positioning result. Does not require a Pi session or project root.",
      keywords: ["emacs-open", "emacsopen", "visit file", "打开文件", "打开文档", "其他窗口", "buffer window"],
      parameters: [{ file: "file path; prefer absolute", placement: "other (Agent default) | here | left | right | above | below | frame",
        line: "optional 1-based line, default 1", col: "optional 0-based column, default 0",
        noFocus: "optional boolean; true keeps the current window/frame focused",
        newWindow: "legacy Markdown clone request; omit with placement", tag: "legacy source tag; omit with placement" }],
    }),
    "noema:api:emacs:surface": documented((body) => apiOpenSurface(body), {
      description: "Open an existing Emacs-hosted Noema surface: Wiki, Agenda or configuration. Check queued/ok; a queued notification does not prove the view is displayed.",
      keywords: ["打开知识库", "打开日程", "配置界面"],
      parameters: [{ path: "/wiki | /agenda | /config, with optional query parameters", client: "optional source pane client id" }],
    }),
    "noema:api:emacs:jupyter-cell": (body) => apiSelectJupyterCell(body),
    "noema:api:emacs:research-session": (body) => apiOpenResearchSession(body),
    "noema:api:emacs:current-file": documented((file) => apiCurrentFile(file), {
      description: "Renderer notification reporting its current file to Emacs. This is a write, not a context query. Agents query emacs:pi action=context for current file/project/selection references.",
      parameters: [{ file: "renderer file path", client: "optional renderer client id" }],
    }),
    "noema:api:emacs:input-focus": (body) => apiEmacsInputFocus(body),
    "noema:api:emacs:ui-state": documented((body) => apiEmacsUiState(body), {
      description: "Renderer notification updating Emacs's page UI state. This is not an editor inspection API; Agents query emacs:pi action=context for source references.",
      parameters: ["renderer UI state object"],
    }),
    "noema:api:emacs:key": documented((key) => apiEmacsKey(key), {
      description: "Forward a renderer keyboard handoff to Emacs. Prefer semantic emacs:open, emacs:surface and emacs:pi/agent operations for Agent actions. This event acknowledgement does not prove an editor action completed.",
      parameters: [{ key: "renderer key name", client: "optional source pane client id", hostOwned: "true only for a key received after Emacs took keyboard ownership" }],
    }),
    "noema:api:emacs:selection": (body) => apiEmacsSelection(body),
    "noema:api:emacs:pi": Object.assign((body) => apiPi(body), { apiDoc: {
      description: "Query the current editor context as references, or manage global/project Pi sessions. Context needs no root and starts nothing. List paginates history (total/nextOffset) and project children (childrenTotal/childrenNextOffset) independently at the same offset/limit. Submission is asynchronous; inspect status or native history for completion.",
      parameters: [{ action: "context | list | status | ensure | send | resume | new | archive",
        root: "absolute local project root", companion: "true for the Emacs companion",
        sessionId: "owned Pi record id for resume/archive", prompt: "required for send",
        from: "send: optional {buffer, nativeSessionId} of the calling Agent session; Pi sees who is asking and can reply to it",
        focus: "optional true for ensure/send; default preserves focus", offset: "list pagination, default 0", limit: "list page size 1..100, default 20" }],
    } }),
    "noema:api:emacs:agent": Object.assign((body) => apiAgent(body), { apiDoc: {
      description: "Emacs owns all ACP sessions. spawn creates a background worker and sends its task after initialization; spawn/send return requestId. result reads only that task, with terminal state and stopReason. Optional notify sends one completion message to the exact parent (busy parents queue it). Background buffers remain manually openable in Agent Manager. create initializes without a prompt; read reads the session transcript excluding drafts; status reports capabilities and usage. Accepted is not completed. No automatic reconnect or permission decisions.",
      parameters: [{ action: "list | tasks | status | create | spawn | send | result | read | stop | show",
        buffer: "required for status/send/read/stop/show: exact buffer name", nativeSessionId: "required for status/send/read/stop/show: exact native ID",
        requestId: "required for result: ID returned by spawn/send; no buffer needed. tasks recovers IDs by root/target, returning lifecycle metadata and original session identity, no prompts or replies. createdAt/finishedAt are Unix seconds. Receipts expire after Emacs exits or bounded eviction",
        root: "optional absolute project fence; required for create/spawn", target: "optional target fence; explicit /fs: paths retain target",
        agent: "required for create/spawn: registered ACP provider identifier, e.g. codex, claude-code, pi",
        name: "create/spawn: optional worker name", background: "create: true keeps the buffer out of ordinary chat tabs/recall; spawn always does",
        modelId: "spawn/background create: optional advertised ACP model ID, scoped to this task session; never changes ordinary defaults",
        effort: "spawn/background create: optional Codex/Claude Code/Pi reasoning level; model/effort are verified before the first task prompt, mismatch fails the task",
        worktree: "create/spawn: optional name; starts the Agent in its own Git worktree of the Project workspace, returned with its branch and path",
        group: "create/spawn with worktree: optional slug recording one attempt of a parallel group",
        prompt: "required for spawn/send: explicit task", files: "spawn/send: optional array of absolute saved file references; no embedded content",
        notify: "spawn/send: optional {buffer, nativeSessionId} of the parent. End your turn to receive its result; do not ask the worker to send a second reply",
        offset: "list/tasks item or read/result character offset, default 0", limit: "list/tasks: 1..100 (default 20); read/result: 1..32000 characters (default 12000)" }],
    } }),
    "noema:api:emacs:system-open": (target) => apiSystemOpen(target),
    "noema:api:emacs:zotero": (body) => apiEmacsZotero(body),
    "noema:api:emacs:zotero-import": (body) => apiEmacsZotero(body, "zotero-import"),
    "noema:api:emacs:choose-note-path": (body) => apiChooseNotePath(body),
  };
}
