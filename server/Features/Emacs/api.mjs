export function createEmacsApiHandlers({
  apiOpenInEmacs,
  apiOpenSurface,
  apiSelectJupyterCell,
	apiOpenResearchSession = () => ({ ok: false }),
  apiCurrentFile,
  apiEmacsInputFocus,
  apiEmacsUiState,
  apiEmacsKey,
  apiEmacsSelection = () => ({ ok: false, message: "Emacs selection bridge unavailable" }),
  apiSystemOpen,
  apiEmacsZotero,
  apiChooseNotePath,
}) {
  return {
    "noema:api:emacs:open": (body) => apiOpenInEmacs(body?.file ?? body, body?.line, body?.col, body?.tag, body),
    "noema:api:emacs:surface": (body) => apiOpenSurface(body),
    "noema:api:emacs:jupyter-cell": (body) => apiSelectJupyterCell(body),
    "noema:api:emacs:research-session": (body) => apiOpenResearchSession(body),
    "noema:api:emacs:current-file": (file) => apiCurrentFile(file),
    "noema:api:emacs:input-focus": (body) => apiEmacsInputFocus(body),
    "noema:api:emacs:ui-state": (body) => apiEmacsUiState(body),
    "noema:api:emacs:key": (key) => apiEmacsKey(key),
    "noema:api:emacs:selection": (body) => apiEmacsSelection(body),
    "noema:api:emacs:system-open": (target) => apiSystemOpen(target),
    "noema:api:emacs:zotero": (body) => apiEmacsZotero(body),
    "noema:api:emacs:zotero-import": (body) => apiEmacsZotero(body, "zotero-import"),
    "noema:api:emacs:choose-note-path": (body) => apiChooseNotePath(body),
  };
}
